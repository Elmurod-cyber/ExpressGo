export const LANGUAGE_SWITCH_ENABLED = true;

let locale: Locale = "uz";

export function getLocale(): Locale {
  return locale;
}

export function setLocale(next: Locale) {
  if (!LANGUAGE_SWITCH_ENABLED) {
    locale = "uz";
    return;
  }
  locale = next === "ru" ? "ru" : "uz";
}

export function t(key: string, vars?: Record<string, string | number>): string {
  const table = locale === "ru" ? ru : uz;
  let text = table[key] ?? uz[key] ?? key;
  if (vars) {
    for (const [name, value] of Object.entries(vars)) {
      text = text.replaceAll(`{${name}}`, String(value));
    }
  }
  return text;
}

export function tx(text: string): string {
  if (locale !== "ru") return text;
  return serverRu[text] ?? text;
}
